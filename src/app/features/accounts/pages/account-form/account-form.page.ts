import { ChangeDetectionStrategy, Component, computed, effect, inject, input, signal, untracked } from '@angular/core';
import { toSignal } from '@angular/core/rxjs-interop';
import { NonNullableFormBuilder, ReactiveFormsModule, Validators } from '@angular/forms';
import { Router, RouterLink } from '@angular/router';
import { finalize } from 'rxjs';
import { ToastService } from '../../../../core/services/toast.service';
import { ApiError } from '../../../../core/models/api-response.model';
import { applyServerErrors } from '../../../../core/utils/api-error.util';
import { FormErrorComponent } from '../../../../shared/components/form-error/form-error.component';
import { IconComponent } from '../../../../shared/components/icon/icon.component';
import { PageHeaderComponent } from '../../../../shared/components/page-header/page-header.component';
import {
  SearchableSelectComponent,
  SearchableSelectOption,
} from '../../../../shared/components/searchable-select/searchable-select.component';
import { StatusPillComponent } from '../../../../shared/components/status-pill/status-pill.component';
import { createQueryResource } from '../../../../shared/list/query-resource';
import { formatMoney } from '../../../../shared/utils/format.util';
import {
  Account,
  ACCOUNT_NATURE_LABEL,
  ACCOUNT_TYPE_VIEW,
  ACCOUNT_TYPES,
  AccountNature,
  AccountPayload,
  AccountType,
} from '../../models/account.model';
import { AccountsService } from '../../services/accounts.service';
import { environment } from '../../../../../environments/environment';
import { ancestorsOf, balanceText, predictChildCode } from '../../utils/account-display.util';

/**
 * Create / edit a chart-of-accounts node. `?id=` edits, `?parentId=` pre-selects
 * the parent for a new account. The type is inherited from the parent; the
 * code is generated by the server (previewed here).
 */
@Component({
  selector: 'app-account-form-page',
  standalone: true,
  changeDetection: ChangeDetectionStrategy.OnPush,
  imports: [ReactiveFormsModule, RouterLink, PageHeaderComponent, IconComponent, FormErrorComponent, SearchableSelectComponent, StatusPillComponent],
  templateUrl: './account-form.page.html',
  styleUrl: './account-form.page.scss',
})
export class AccountFormPage {
  private readonly fb = inject(NonNullableFormBuilder);
  private readonly api = inject(AccountsService);
  private readonly toast = inject(ToastService);
  private readonly router = inject(Router);

  /** Bound from route data / query string. */
  readonly navId = input.required<string>();
  readonly id = input<string>();
  readonly parentId = input<string>();

  private readonly reload = signal(0);
  protected readonly chart = createQueryResource(this.reload, () => this.api.list());
  protected readonly accounts = computed(() => this.chart.value() ?? []);
  private readonly ready = computed(() => this.accounts().length > 0);

  protected readonly types = ACCOUNT_TYPES;
  protected readonly typeView = ACCOUNT_TYPE_VIEW;
  protected readonly natureLabel = ACCOUNT_NATURE_LABEL;
  protected readonly natures: readonly AccountNature[] = ['debit', 'credit'];
  protected readonly money = formatMoney;

  protected readonly form = this.fb.group({
    parentId: [''],
    name: ['', [Validators.required, Validators.minLength(2), Validators.maxLength(100)]],
    type: ['asset' as AccountType, Validators.required],
    nature: ['debit' as AccountNature, Validators.required],
    isGroup: [false],
    openingBalance: [0],
    costCenterRequired: [false],
    notes: ['', Validators.maxLength(300)],
    isActive: [true],
  });

  protected readonly isEdit = computed(() => !!this.id());
  protected readonly current = computed<Account | null>(() => this.accounts().find((a) => a.id === this.id()) ?? null);
  protected readonly saving = signal<'save' | 'saveNew' | null>(null);

  private readonly draft = toSignal(this.form.valueChanges, { initialValue: this.form.getRawValue() });
  private readonly value = computed(() => ({ ...this.form.getRawValue(), ...this.draft() }));

  /** Group accounts as parent options (the edited account's own subtree excluded). */
  protected readonly parentOptions = computed<SearchableSelectOption[]>(() =>
    this.accounts()
      .filter((a) => a.isGroup && a.isActive && a.id !== this.id())
      .map((a) => ({ value: a.id, label: `${a.code} — ${a.name}`, hint: `${ACCOUNT_TYPE_VIEW[a.type].label} · المستوى ${a.level}` })),
  );

  protected readonly parent = computed(() => this.accounts().find((a) => a.id === this.value().parentId) ?? null);

  /** Path shown in the preview: ancestors → parent → this account. */
  protected readonly path = computed(() => {
    const parent = this.parent();
    return parent ? [...ancestorsOf(this.accounts(), parent.id), parent] : [];
  });

  protected readonly code = computed(() => this.current()?.code ?? predictChildCode(this.accounts(), this.value().parentId || null));
  protected readonly balance = computed(() => {
    const c = this.current();
    return c ? balanceText(c) : null;
  });

  constructor() {
    // Type & nature follow the parent; type locks when a parent is chosen.
    this.form.controls.parentId.valueChanges.subscribe(() => this.syncFromParent());
    this.form.controls.type.valueChanges.subscribe((type) => {
      if (!this.isEdit()) this.form.controls.nature.setValue(ACCOUNT_TYPE_VIEW[type].nature, { emitEvent: false });
    });
    this.form.controls.isGroup.valueChanges.subscribe((group) => {
      const opening = this.form.controls.openingBalance;
      if (group) {
        opening.setValue(0);
        this.form.controls.costCenterRequired.setValue(false);
      }
    });

    // Seed the form once the chart has loaded, and whenever ?id= / ?parentId= change.
    // (`ready` flips once, so a background reload doesn't wipe what's being typed.)
    effect(() => {
      const ready = this.ready();
      const id = this.id();
      const parentId = this.parentId();
      if (!ready) return;
      untracked(() => (id ? this.loadForEdit(id) : this.resetForCreate(parentId ?? '')));
    });
  }

  protected submit(mode: 'save' | 'saveNew'): void {
    if (this.form.invalid) {
      this.form.markAllAsTouched();
      this.toast.warning('راجع الحقول المطلوبة قبل الحفظ');
      return;
    }
    const v = this.form.getRawValue();
    const payload: AccountPayload = {
      name: v.name.trim(),
      parentId: v.parentId || null,
      type: v.type,
      nature: v.nature,
      isGroup: v.isGroup,
      costCenterRequired: !v.isGroup && v.costCenterRequired,
      // Single-currency ledger: every account is in the base currency (EGP).
      currency: environment.currency,
      openingBalance: v.isGroup ? 0 : Number(v.openingBalance) || 0,
      notes: v.notes.trim(),
      isActive: v.isActive,
    };
    const id = this.id();
    this.saving.set(mode);
    (id ? this.api.update(id, payload) : this.api.create(payload))
      .pipe(finalize(() => this.saving.set(null)))
      .subscribe({
        next: (acc) => {
          this.toast.success(id ? 'تم تحديث الحساب' : `تم إضافة الحساب ${acc.code} — ${acc.name}`);
          if (mode === 'saveNew') {
            // Same parent, ready for the next sibling.
            this.reload.update((n) => n + 1);
            this.resetForCreate(payload.parentId ?? '');
          } else {
            this.router.navigate(['/accounts/chart']);
          }
        },
        error: (err: ApiError) => applyServerErrors(this.form, err),
      });
  }

  private loadForEdit(id: string): void {
    const a = this.accounts().find((x) => x.id === id);
    if (!a) {
      this.toast.warning('الحساب غير موجود');
      this.router.navigate(['/accounts/card'], { replaceUrl: true });
      return;
    }
    this.form.reset(
      {
        parentId: a.parentId ?? '',
        name: a.name,
        type: a.type,
        nature: a.nature,
        isGroup: a.isGroup,
        openingBalance: a.openingBalance,
        costCenterRequired: a.costCenterRequired,
        notes: a.notes,
        isActive: a.isActive,
      },
      { emitEvent: false },
    );
    // Parent can't move after creation; system accounts keep their kind.
    this.form.controls.parentId.disable({ emitEvent: false });
    this.form.controls.type.disable({ emitEvent: false });
    if (a.isSystem) {
      this.form.controls.isGroup.disable({ emitEvent: false });
      this.form.controls.isActive.disable({ emitEvent: false });
    } else {
      this.form.controls.isGroup.enable({ emitEvent: false });
      this.form.controls.isActive.enable({ emitEvent: false });
    }
    this.form.updateValueAndValidity();
  }

  private resetForCreate(parentId: string): void {
    this.form.controls.parentId.enable({ emitEvent: false });
    this.form.controls.isGroup.enable({ emitEvent: false });
    this.form.controls.isActive.enable({ emitEvent: false });
    this.form.reset({ parentId }, { emitEvent: false });
    this.syncFromParent();
    this.form.updateValueAndValidity();
  }

  private syncFromParent(): void {
    const parent = this.accounts().find((a) => a.id === this.form.controls.parentId.value);
    const type = this.form.controls.type;
    if (parent) {
      type.setValue(parent.type, { emitEvent: false });
      type.disable({ emitEvent: false });
      if (!this.isEdit()) this.form.controls.nature.setValue(ACCOUNT_TYPE_VIEW[parent.type].nature, { emitEvent: false });
    } else if (!this.isEdit()) {
      type.enable({ emitEvent: false });
      this.form.controls.nature.setValue(ACCOUNT_TYPE_VIEW[type.value].nature, { emitEvent: false });
    }
    this.form.updateValueAndValidity();
  }
}
