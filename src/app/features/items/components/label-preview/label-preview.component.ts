import { ChangeDetectionStrategy, Component, computed, inject, input, ViewEncapsulation } from '@angular/core';
import { DomSanitizer, SafeHtml } from '@angular/platform-browser';
import { LabelFields, LabelRow, LabelTemplate } from '../../models/barcode-label.model';
import { labelCss, labelHtml } from '../../utils/print-labels';

/** On-screen zoom so a 38×25 mm label is readable. */
const ZOOM = 2;

/**
 * True-to-size label preview, built from the exact markup and CSS the print
 * window uses (WYSIWYG). Shadow DOM keeps the label styles out of the app.
 */
@Component({
  selector: 'app-label-preview',
  standalone: true,
  changeDetection: ChangeDetectionStrategy.OnPush,
  encapsulation: ViewEncapsulation.ShadowDom,
  template: `
    <div class="stage">
      <div class="zoom" [style.zoom]="zoom" [innerHTML]="html()"></div>
      <small>المقاس الفعلي {{ template().width }}×{{ template().height }} مم — المعاينة مكبّرة ×{{ zoom }}</small>
    </div>
  `,
  styles: `
    :host { display: block; }
    .stage { display: flex; flex-direction: column; align-items: center; gap: 10px; padding: 18px 10px;
             border-radius: 12px; background: repeating-conic-gradient(#0000000a 0 25%, transparent 0 50%) 0 0 / 16px 16px; }
    .zoom { box-shadow: 0 4px 18px rgb(0 0 0 / 0.18); border-radius: 1.5px; overflow: hidden; }
    small { font: 11px/1.4 "IBM Plex Sans Arabic", "Segoe UI", sans-serif; color: #888; }
  `,
})
export class LabelPreviewComponent {
  private readonly sanitizer = inject(DomSanitizer);

  readonly row = input.required<Pick<LabelRow, 'item'>>();
  readonly template = input.required<LabelTemplate>();
  readonly fields = input.required<LabelFields>();

  protected readonly zoom = ZOOM;

  /**
   * Trusted on purpose: every value is HTML-escaped by `labelHtml`, and the SVG
   * (which Angular's sanitizer would strip) is generated by our own encoder.
   */
  protected readonly html = computed<SafeHtml>(() =>
    this.sanitizer.bypassSecurityTrustHtml(
      `<style>${labelCss(this.template())}</style>${labelHtml(this.row(), this.fields())}`,
    ),
  );
}
